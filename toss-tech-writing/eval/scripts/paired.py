"""Build paired blind sheet: original Toss article vs generated article on the same facts.
usage: python3 -I paired.py <out_dir> <seed> <name>=<original.md>,<generated.md> ...
Both texts are normalized the same way: no title/subtitle/byline, no images, tables, code,
callout markers, bold, placeholders, CTA lines.
"""
import json, os, random, re, sys


def norm(path, original):
    t = open(path, encoding="utf-8").read()
    if t.startswith("---\n"):
        t = t.split("---\n", 2)[2]
    t = re.sub(r"\s*\[확인 필요[^\]]*\]", "", t)
    out, inc = [], False
    lines = [l.rstrip() for l in t.splitlines()]
    for i, l in enumerate(lines):
        s = l.strip()
        if s.startswith("```"):
            inc = not inc
            continue
        if inc or not s:
            continue
        if s.startswith("# "):
            continue
        if re.search(r"\d{4}년 \d+월 \d+일$", s):
            continue
        if s.startswith(("[이미지", "![", "[콜아웃", "[표", "[캡션", "[동영상", "|", "*캡션")) or s in ("---",):
            continue
        if "[!NOTE]" in s or "[!TIP]" in s or "TODO" in s:
            continue
        if any(k in s for k in ("지원하기", "궁금하다면?", "님의 다른 글", "일해보고 싶다면")):
            continue
        if not original and not out and not s.startswith(("안녕하세요", ">")) and len(s) < 160 and " · " not in s:
            continue  # generated subtitle/lead line before the body starts
        if not original and len(out) < 3 and " · " in s:
            continue  # generated byline
        s = s.replace("**", "")
        s = re.sub(r"^\d+[.)] ", "- ", s)  # ordered-list numbering differs between scraper and markdown
        s = re.sub(r"^>\s*", "", s)
        out.append(s)
    return "\n\n".join(out)


out_dir, seed = sys.argv[1], int(sys.argv[2])
rng = random.Random(seed)
os.makedirs(out_dir, exist_ok=True)
sheet, key = [], {}
for arg in sys.argv[3:]:
    name, paths = arg.split("=")
    orig, gen = paths.split(",")
    a, b = norm(orig, True), norm(gen, False)
    if rng.random() < 0.5:
        x, y, ans = a, b, "Y"
    else:
        x, y, ans = b, a, "X"
    key[name] = ans
    sheet.append(f"# 짝 {len(sheet)+1}\n\n## 글 X\n\n{x}\n\n## 글 Y\n\n{y}")
open(os.path.join(out_dir, "pairs.md"), "w").write("\n\n=====\n\n".join(sheet))
json.dump(key, open(os.path.join(out_dir, "key.json"), "w"))
print("pairs:", len(sheet), "(key hidden)")
